import { describe, expect, it } from 'vitest'

import { normalizeBarcode } from './barcode'

describe('normalizeBarcode', () => {
  it.each([
    ['4006381333931', '4006381333931'],
    ['5901234123457', '5901234123457'],
    ['73513537', '73513537'],
    // UPC-A — тот же EAN-13 без ведущего нуля.
    ['036000291452', '0036000291452'],
    ['0036000291452', '0036000291452'],
    // Как на упаковке: с пробелами и дефисами.
    ['  4 006381 333931 ', '4006381333931'],
    ['4-006381-333931', '4006381333931'],
  ])('%s — штрихкод %s', (text, expected) => {
    expect(normalizeBarcode(text)).toBe(expected)
  })

  it.each([
    '',
    '   ',
    // Одна цифра не та — контрольная не сходится.
    '4006381333932',
    '73513536',
    '036000291453',
    // Не та длина.
    '7351353',
    '400638133',
    '04006381333931',
    '40063813339ab',
    '４００６３８１３３３９３１',
    'https://example.com/4006381333931',
  ])('«%s» — не штрихкод', (text) => {
    expect(normalizeBarcode(text)).toBeNull()
  })
})
