import { expect, test } from '@playwright/test'
import { adminInviteLink, register } from './steps.ts'

test('анализы и давление: ввод без сети, отправка, правка и удаление', async ({
  page,
  context,
}, testInfo) => {
  await register(
    page,
    adminInviteLink(),
    'Анна',
    `labs-${testInfo.project.name}-${Date.now()}@example.com`,
  )
  const more = page.getByRole('link', { name: 'Ещё' })
  if (await more.isVisible()) await more.click()
  await page.getByRole('link', { name: 'Анализы', exact: true }).click()
  await page.evaluate(() => navigator.serviceWorker.ready)
  await page.reload()
  await page.waitForLoadState('networkidle')
  await context.setOffline(true)
  await page.reload()
  await page.getByRole('link', { name: 'Новый бланк' }).click()
  await page.getByLabel('Лаборатория').fill('Инвитро')
  await page.getByRole('button', { name: 'Создать бланк' }).click()
  await page.getByRole('link', { name: 'Гемоглобин', exact: true }).click()
  await page.getByLabel('Значение', { exact: true }).fill('100')
  await page.getByLabel('От', { exact: true }).fill('120')
  await page.getByLabel('До', { exact: true }).fill('160')
  await page.getByRole('button', { name: 'Добавить', exact: true }).click()
  await expect(page.getByRole('img', { name: 'ниже референса' })).toBeVisible()
  await expect(page.getByRole('img', { name: 'Ещё не отправлено' }).first()).toBeVisible()
  const reportUrl = page.url()
  await page.screenshot({ path: testInfo.outputPath('lab-report.png'), fullPage: true })
  await context.setOffline(false)
  await page.evaluate(() => window.dispatchEvent(new Event('online')))
  await expect(page.getByRole('img', { name: 'Ещё не отправлено' })).toHaveCount(0)
  await page.reload()
  await page.getByRole('link', { name: /Гемоглобин/ }).click()
  await page.getByText('г/дл', { exact: true }).click()
  await expect(page.getByRole('radio', { name: 'г/дл', exact: true })).toBeChecked()
  await expect(page.getByLabel('От', { exact: true })).toHaveValue('12')
  await page.getByLabel('Значение', { exact: true }).fill('14.2')
  await page.getByRole('button', { name: 'Сохранить' }).click()
  await expect(page.getByRole('img', { name: 'ниже референса' })).toHaveCount(0)
  await page.goto('/measurements/metrics/new')
  await page.getByRole('button', { name: 'Добавить: Давление', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Добавить: Давление', exact: true })).toHaveCount(0)
  await page.goto('/measurements/pressure/new')
  await page.waitForLoadState('networkidle')
  await context.setOffline(true)
  await page.reload()
  await page.getByLabel('Верхнее').fill('140')
  await page.getByLabel('Нижнее').fill('90')
  await page.getByLabel('Пульс, необязательно').fill('72')
  await page.getByRole('button', { name: 'Сохранить' }).click()
  await expect(page.getByText('выше 135/85').first()).toBeVisible()
  await expect(page.getByRole('img', { name: 'Ещё не отправлено' }).first()).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('pressure.png'), fullPage: true })
  await context.setOffline(false)
  await page.evaluate(() => window.dispatchEvent(new Event('online')))
  await expect(page.getByRole('img', { name: 'Ещё не отправлено' })).toHaveCount(0)
  await page.reload()
  await expect(page.getByRole('list', { name: 'История' })).toContainText('140/90')
  await page.getByRole('button', { name: 'Удалить', exact: true }).click()
  await page.getByRole('button', { name: 'Да, удалить' }).click()
  await expect(page.getByText('Замеров давления пока нет.').first()).toBeVisible()
  await page.goto(reportUrl)
  await page.getByRole('button', { name: 'Удалить бланк' }).click()
  await page.getByRole('button', { name: 'Да, удалить' }).click()
  await expect(page.getByText(/Бланков пока нет/)).toBeVisible()
})
