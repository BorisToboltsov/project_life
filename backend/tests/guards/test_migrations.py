@pytest.fixture
def at_head() -> Iterator[None]:
    """Что бы ни случилось в тесте, база возвращается к последней миграции."""
    yield
    command.upgrade(alembic_config(), "head")


def _rows(query: LiteralString, *params: Any) -> list[tuple[Any, ...]]:
    with psycopg.connect(sync_url()) as connection:
        return connection.execute(query, params).fetchall()


def _execute(query: LiteralString, *params: Any) -> None:
    with psycopg.connect(sync_url(), autocommit=True) as connection:
        connection.execute(query, params)


@pytest.mark.usefixtures("at_head")
def test_meal_migration_carries_the_diary_over_and_back() -> None:
    """Данные фазы 3 переживают переход к списку приёмов пищи и откат с него."""
    config = alembic_config()
    user, product = uuid.uuid7(), uuid.uuid7()
    command.downgrade(config, BEFORE_MEALS)
    _execute(
        "INSERT INTO users (id, email, password_hash, display_name, role, language, timezone,"
        " unit_system, disclaimer_accepted_at)"
        " VALUES (%s, 'anna@example.com', 'x', 'Анна', 'user', 'ru', 'Europe/Moscow', 'metric',"
        " now())",
        user,
    )
    _execute(
        "INSERT INTO products (id, name, kcal, protein_g, fat_g, carbs_g, created_by)"
        " VALUES (%s, 'Творог 5 %%', 121, 17.2, 5, 1.8, %s)",
        product,
        user,
    )
    for meal, amount in (("breakfast", 150), ("snack", 60)):
        _execute(
            "INSERT INTO food_entries (id, user_id, local_date, meal, amount_g, product_id,"
            " product_name, kcal, protein_g, fat_g, carbs_g)"
            " VALUES (%s, %s, %s, %s, %s, %s, 'Творог 5 %%', 121, 17.2, 5, 1.8)",
            uuid.uuid7(),
            user,
            date(2026, 10, 11),
            meal,
            amount,
            product,
        )
    _execute(
        "INSERT INTO nutrition_goals (user_id, effective_from, kcal, protein_g, fat_g, carbs_g)"
        " VALUES (%s, %s, 2100, 130, 70, 230)",
        user,
        date(2026, 10, 1),
    )

    command.upgrade(config, MEALS)

    meals = _rows("SELECT id, preset, position, name, archived_at FROM meals ORDER BY position")
    assert [meal[1:] for meal in meals] == [
        ("breakfast", 0, None, None),
        ("lunch", 1, None, None),
        ("dinner", 2, None, None),
        ("snack", 3, None, None),
    ]
    # Ключи приёмов годятся для запросов клиента: это UUIDv7.
    assert {meal[0].version for meal in meals} == {7}
    assert _rows(
        "SELECT meals.preset, amount::int, unit FROM food_entries"
        " JOIN meals ON meals.id = meal_id ORDER BY amount"
    ) == [("snack", 60, "g"), ("breakfast", 150, "g")]
    assert _rows("SELECT unit FROM products") == [("g",)]

    # Свой приём пищи и цель без калорий прежняя схема выразить не может.
    own = uuid.uuid7()
    _execute(
        "INSERT INTO meals (id, user_id, name, position) VALUES (%s, %s, 'Полдник', 4)", own, user
    )
    _execute("UPDATE food_entries SET meal_id = %s WHERE amount = 150", own)
    _execute(
        "INSERT INTO nutrition_goals (user_id, effective_from, protein_g) VALUES (%s, %s, 150)",
        user,
        date(2026, 10, 11),
    )

    command.downgrade(config, BEFORE_MEALS)

    assert _rows("SELECT meal, amount_g::int FROM food_entries ORDER BY amount_g") == [
        ("snack", 60),
        ("snack", 150),
    ]
    assert _rows("SELECT kcal FROM nutrition_goals") == [(2100,)]


@pytest.mark.usefixtures("at_head")
def test_metric_migration_carries_the_measurements_over_and_back() -> None:
    """Замеры фазы 2 переживают переход к списку видов замеров и откат с него."""
    config = alembic_config()
    user, other = uuid.uuid7(), uuid.uuid7()
    command.downgrade(config, BEFORE_METRICS)
    for user_id, email in ((user, "anna@example.com"), (other, "boris@example.com")):
        _execute(
            "INSERT INTO users (id, email, password_hash, display_name, role, language, timezone,"
            " unit_system, disclaimer_accepted_at)"
            " VALUES (%s, %s, 'x', 'Анна', 'user', 'ru', 'Europe/Moscow', 'metric', now())",
            user_id,
            email,
        )

    for owner, metric, value, unit in (
        (user, "weight", 72.4, "kg"),
        (user, "waist", 86, "cm"),
        (other, "weight", 90, "kg"),
    ):
        _execute(
            "INSERT INTO measurements (id, user_id, metric, value, original_value,"
            " original_unit, measured_at, local_date, source)"
            " VALUES (%s, %s, %s, %s, %s, %s, now(), %s, 'manual')",
            uuid.uuid7(),
            owner,
            metric,
            value,
            value,
            unit,
            date(2026, 10, 11),
        )

    command.upgrade(config, METRICS)

    metrics = _rows(
        "SELECT id, preset, quantity, position, name, archived_at FROM metrics"
        " WHERE user_id = %s ORDER BY position",
        user,
    )
    assert [metric[1:] for metric in metrics] == [
        ("weight", "mass", 0, None, None),
        ("neck", "length", 1, None, None),
        ("waist", "length", 2, None, None),
        ("hips", "length", 3, None, None),
    ]
    # Ключи видов годятся для запросов клиента: это UUIDv7.
    assert {metric[0].version for metric in metrics} == {7}
    # Каждый замер привязан к виду своего владельца.
    assert _rows(
        "SELECT users.email, metrics.preset, measurements.value::float FROM measurements"
        " JOIN metrics ON metrics.id = metric_id AND metrics.user_id = measurements.user_id"
        " JOIN users ON users.id = measurements.user_id ORDER BY value"
    ) == [
        ("anna@example.com", "weight", 72.4),
        ("anna@example.com", "waist", 86.0),
        ("boris@example.com", "weight", 90.0),
    ]

    # Свой вид, рекомендуемый вид и проценты прежняя схема выразить не может.
    own, body_fat = uuid.uuid7(), uuid.uuid7()
    _execute(
        "INSERT INTO metrics (id, user_id, name, quantity, position)"
        " VALUES (%s, %s, 'Запястье', 'length', 4)",
        own,
        user,
    )
    _execute(
        "INSERT INTO metrics (id, user_id, preset, quantity, position)"
        " VALUES (%s, %s, 'body_fat', 'percent', 5)",
        body_fat,
        user,
    )
    for metric_id, value, unit in ((own, 16.5, "cm"), (body_fat, 18.5, "percent")):
        _execute(
            "INSERT INTO measurements (id, user_id, metric_id, value, original_value,"
            " original_unit, measured_at, local_date, source)"
            " VALUES (%s, %s, %s, %s, %s, %s, now(), %s, 'manual')",
            uuid.uuid7(),
            user,
            metric_id,
            value,
            value,
            unit,
            date(2026, 10, 11),
        )

    command.downgrade(config, BEFORE_METRICS)

    assert _rows("SELECT metric, value::float, original_unit FROM measurements ORDER BY value") == [
        ("weight", 72.4, "kg"),
        ("waist", 86.0, "cm"),
        ("weight", 90.0, "kg"),
    ]
